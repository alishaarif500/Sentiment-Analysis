# 5. Standard PyTorch Training & Validation Loop
import time
import torch

if 'model' not in globals() or 'train_loader' not in globals():
    raise NameError("Please run cells 3910464c and 220b12cd to set up the data loaders, model, and optimizer first.")

for epoch in range(epochs):
    print(f"\n======== Epoch {epoch + 1} / {epochs} ========")

    # =========================================
    #               TRAINING
    # =========================================
    model.train()
    total_train_loss = 0
    correct_train_preds = 0
    total_train_samples = 0

    start_time = time.time()

    # Limit processing to first 50 batches for quick verification if CPU is active
    max_batches = len(train_loader) if torch.cuda.is_available() else 50
    if not torch.cuda.is_available():
         print("Running on CPU: Limiting to first 50 batches for quick prototype execution.")

    for step, batch in enumerate(train_loader):
        if step >= max_batches:
            break

        # Unpack outputs and move to device
        input_ids = batch['input_ids'].to(device)
        attention_mask = batch['attention_mask'].to(device)
        labels = batch['label'].to(device)

        # Clear previously calculated gradients
        model.zero_grad()

        # Forward pass
        outputs = model(input_ids=input_ids, attention_mask=attention_mask)
        logits = outputs.logits

        # Calculate Loss
        loss = loss_fn(logits, labels)
        total_train_loss += loss.item()

        # Calculate Accuracy
        _, preds = torch.max(logits, dim=1)
        correct_train_preds += torch.sum(preds == labels).item()
        total_train_samples += labels.size(0)

        # Backward pass
        loss.backward()

        # Clip gradients to prevent exploding gradients
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)

        # Update parameters and learning rate
        optimizer.step()
        scheduler.step()

        if step % 10 == 0 and step > 0:
            elapsed = time.time() - start_time
            print(f"  Batch {step:>5} of {max_batches:>5}. Loss: {loss.item():.4f}. Elapsed: {elapsed:.2f}s")

    avg_train_loss = total_train_loss / max_batches
    train_acc = correct_train_preds / total_train_samples

    # =========================================
    #               VALIDATION
    # =========================================
    model.eval()
    total_val_loss = 0
    correct_val_preds = 0
    total_val_samples = 0

    max_val_batches = len(val_loader) if torch.cuda.is_available() else 15

    with torch.no_grad():
        for val_step, batch in enumerate(val_loader):
            if val_step >= max_val_batches:
                break

            input_ids = batch['input_ids'].to(device)
            attention_mask = batch['attention_mask'].to(device)
            labels = batch['label'].to(device)

            outputs = model(input_ids=input_ids, attention_mask=attention_mask)
            logits = outputs.logits

            loss = loss_fn(logits, labels)
            total_val_loss += loss.item()

            _, preds = torch.max(logits, dim=1)
            correct_val_preds += torch.sum(preds == labels).item()
            total_val_samples += labels.size(0)

    avg_val_loss = total_val_loss / max_val_batches
    val_acc = correct_val_preds / total_val_samples

    print(f"\n  [Epoch {epoch+1} Results] ")
    print(f"  Training Loss: {avg_train_loss:.4f} | Training Acc: {train_acc:.4f}")
    print(f"  Val Loss:      {avg_val_loss:.4f} | Val Acc:      {val_acc:.4f}")

    # Save metrics history
    training_history['train_loss'].append(avg_train_loss)
    training_history['train_acc'].append(train_acc)
    training_history['val_loss'].append(avg_val_loss)
    training_history['val_acc'].append(val_acc)

